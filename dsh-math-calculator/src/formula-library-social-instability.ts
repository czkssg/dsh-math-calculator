/**
 * 公式库第三十一批：**社会失稳判据（P5）—— 最容易写错的一类**。
 *
 * ## 为什么这批要特别小心
 *
 * 前四批（过程、饥荒、生产、地质）都有**物理或统计的硬锚**可以核对。
 * 社会失稳没有 —— 它既不能验证，又极易被当成「预言」使用。
 *
 * ```
 *   ✓ 可以说：缺口 70% 时死亡率约 17%（有历史锚）
 *   ✗ 不能说：这个王朝会在第 37 年崩（没有可靠模型）
 * ```
 *
 * 所以本批的**每一条都在 desc 里写明「这是量级判据，不是预测」**，
 * 且**只收有明确结构关系的式子**，不收「拟合历史周期」的东西。
 *
 * ## 本批的组织：三个不同层次
 *
 * ```
 *   ① 生存压力（饥荒/税负 → 不满）      —— 可量化
 *   ② 组织能力（能不能真的起来造反）    —— 结构判据
 *   ③ 精英动力学（上层的内斗）          —— 最经典也最可靠的一层
 * ```
 *
 * 第 ③ 层是本批最有价值的：**「精英过剩」是王朝崩溃里最稳定的一条模式**
 * （Turchin 的 cliodynamics、中国历代党争、罗马晚期的权力斗争），
 * 而且它能写成很清楚的比率。
 *
 * ## 明确不做的一条
 *
 * **不做「王朝寿命预测」**。历史周期律是**描述**，不是公式 ——
 * 把它做成一条 expr 会给出（比如）「这个王朝还剩 87 年」这种荒谬的精确。
 *
 * @module dsh-math-calculator/formula-library-social-instability
 */

