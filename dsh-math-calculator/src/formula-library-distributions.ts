/**
 * 公式库第二十三批：**概率分布的闭式矩与分位（补 dist 的分布缺口）**。
 *
 * ## 为什么这批不该做成「公式」，而该做成公式
 *
 * `dist` operation 已支持 normal / binomial / poisson / exponential 四种。
 * 但冷战到千禧年这一段工程与可靠性最常用的**另外几种**，全都没有：
 *
 * ```
 *   Weibull      疲劳/寿命分析的标准分布（形状参数是它的全部价值）
 *   对数正态     收入、粒径、修复时间 —— 乘法过程的结果
 *   卡方         方差检验、拟合优度
 * ```
 *
 * 它们现有的缺失不是「少一个 CDF」，而是**连基本矩都算不出来**。
 * 而矩（均值/方差）恰好都有闭式，正好符合本库「只收闭合式」的判据。
 *
 * ## 这批的定位：不是替代 dist，是补它的前提
 *
 * ```
 *   dist      → 给一个点上的概率密度/累积（需要完整参数）
 *   本条一批  → 给「这个分布长什么样」（均值/方差/中位/失效率）
 * ```
 *
 * 也就是说：**先用这批判断「该用哪个分布、参数大概多少」，再用 dist 算点值**。
 * 分工写在 desc 里，避免用户重复算同一件事。
 *
 * ## 一处必须诚实的地方
 *
 * Weibull 的**形状参数 k** 是唯一真正重要的参数，而它没有理论值 —— 必须来自数据。
 * 所以本批的价值不是「替你算 k」，而是「告诉你 k 取不同值意味着失效模式完全不同」：
 *
 * ```
 *   k < 1   早期失效（越用越不容易坏）
 *   k = 1   随机失效（与 exponential 相同）
 *   k > 1   磨损失效（越用越容易坏）
 * ```
 *
 * @module dsh-math-calculator/formula-library-distributions
 */

