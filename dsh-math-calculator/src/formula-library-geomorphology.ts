/**
 * 公式库第三十批：**地质速率（P4）—— 世界的时间深度**。
 *
 * ## 缺口在哪
 *
 * 现有 95 条 `perception/*` 都是「站在地面上看到什么」（地平线、日长、体感温度）。
 * 缺的是**地形怎么形成、怎么变化**：
 *
 * ```
 *   缺：侵蚀多快（削平一座山要多久）
 *   缺：土壤形成多快（多厚土要多少年）
 *   缺：河流搬沙（三角洲多快长成）
 *   缺：海岸线变化、地下水补给
 * ```
 *
 * ## 为什么这一层决定「世界的真实感」
 *
 * 一个世界的**时间深度**由地质速率决定：
 *
 * ```
 *   「这片平原是三万年冲出来的」 vs 「这里一直是这样」
 *   是两种完全不同的世界 —— 前者有历史，后者只是个背景板。
 * ```
 *
 * 而**土壤形成速率**尤其关键：它把「地力衰减」（已有 `soil_nutrient_balance`）
 * 和「土地不可再生」连起来 —— 这正是「古代文明为何因土地耗尽而崩」的定量根据。
 *
 * ## 本批的判据：只给速率与量级，不给绝对年代
 *
 * 地质学的所有数字都是**速率 × 时间**。所以本批只给「X 速率」，
 * 让调用方自己乘时间 —— 因为**每个世界的时间尺度不同**，
 * 硬编码「某山 100 万年前形成」是错的。
 *
 * @module dsh-math-calculator/formula-library-geomorphology
 */

