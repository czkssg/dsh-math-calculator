/**
 * 公式库第二十九批：**日常生产的实物链（P3）—— 前工业社会的真实成本**。
 *
 * ## 缺口在哪
 *
 * 现有工艺公式集中在**金属、窑炉、化工**（重工业）。但前工业社会里，
 * 普通人一生接触最多的生产活动是**纺织**，其次是**食物保存**与**建筑材料**。
 *
 * ```
 *   已有：炼铁收得率、窑炉热平衡、蒸馏塔板数、齿轮强度
 *   没有：一斤羊毛能纺多少线、织一匹布要多少人日、
 *        腌一缸菜要多少盐、烧一窑砖要多少柴
 * ```
 *
 * 后者才是「这一千人的聚落怎么过日子」。而且这些数字**历史上有硬锚**，
 * 可以交叉验证 —— 不像很多社会参数只能拍。
 *
 * ## 本批的判据：必须有「人日」这个共同单位
 *
 * 前工业生产的核心约束是**劳动力**，不是能量也不是资本。
 * 所以本批所有公式都尽可能输出或接受「人日」：
 *
 * ```
 *   纺织：每匹布要多少人日 → 一个聚落能产多少布 → 够不够穿
 *   造纸：每令纸要多少人日 → 能不能维持一个文书体系
 *   制盐：每吨盐要多少柴 → 盐贵不贵 → 肉能不能腌
 * ```
 *
 * **「人日」让不同行业可比** —— 这是本批最重要的设计。
 *
 * ## 一处必须写明的历史锚
 *
 * 纺织的数据最可靠（英国工业革命前的工资册、行会记录）。
 * 我用的是「手工纺纱约 10~20 人日/磅纱」这个量级，
 * 而**珍妮机把它降到 0.1 人日** —— 这个 100 倍差距正是工业革命的核心。
 *
 * @module dsh-math-calculator/formula-library-craft-production
 */

