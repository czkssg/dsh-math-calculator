/**
 * 经验公式的底层原理拆解：区分「物理内核」与「纯标定」，并明确标注哪些只在现实宇宙成立。
 *
 * ## 对上一版的自纠（2026-10-26 修订）
 *
 * 上一版把 `hull_speed` 归为 `scalable`（可泛化），理由是
 * 「1.34 = Fr·√g 组合，换重力就能重算」。**这个判断过头了。**
 *
 * 真实的物理内核只有 Froude 数本身：
 *
 *   v = Fr · √(g·L)      ← 这是**量纲分析**的结论，跨世界成立
 *   Fr ≈ 0.4             ← 这是**经验值**，来自地球船舶的观测
 *
 * 而 Fr ≈ 0.4 是怎么来的？它是「兴波阻力急剧上升」的临界点，
 * 本质上由**自由液面重力波的色散关系**决定：
 *
 *   波速 c = √(g·λ/(2π))        ← 深水重力波，**含 1/(2π)**
 *   兴波极限 ≈ 船速追上自己的船首波 → 波长 ≈ 船长 L
 *   代入得 v_limit ≈ √(g·L/(2π)) ≈ 0.4·√(g·L)
 *
 * 所以 Fr ≈ 0.4 ≈ 1/√(2π) **不是纯粹的经验拟合，而是色散关系的推论**。
 * 这一点上一版说错了：它不是「地球船舶的经验常数」，而是物理推出来的。
 *
 * ## 但 Fr 的推导仍依赖「水」这个介质
 *
 * 1/(2π) 来自重力的**色散关系**（ω² = g·k），本身与介质无关；
 * 但 `Fr ≈ 0.4` 的**数值**还隐含：
 *   · 介质是**液体**（有自由表面）
 *   · 表面张力可忽略（内河船长尺度下成立）
 *   · 兴波阻力主导（黏性阻力次要）
 *
 * 换一个**液体介质**（液氨、液态甲烷、岩浆），色散关系中的表面张力与黏性会变，
 * 临界 Fr 会移动。所以：
 *   · **量纲形式** Fr·√(g·L) → 跨世界成立
 *   · **数值 0.4** → 只在「类水液体 + 宏观尺度」域成立
 *
 * ## 结论：三级标注，而不是两级
 *
 * | 级别 | 含义 | 例 |
 * |---|---|---|
 * | `dimensionless` | 量纲/标度形式跨世界成立，数值也无需改 | 克莱伯指数 0.75 |
 * | `scalable-with-caveat` | **形式**可泛化，但**系数**需重新标定或验证 | Froude 0.4、潮汐系数 |
 * | `earth-only` | 形式本身就是地球拟合，换世界无意义 | Mifflin 代谢、风寒、Du Bois |
 *
 * 上一版把 `hull_speed` 放在 `dimensionless` 那一侧，等于宣称
 * 「0.4 换世界也精确成立」——那是**过度自信**。现在它被降级到 middle 档。
 *
 * @module dsh-math-calculator/empirical-decomposition
 */

/** 拆解类型（三级）。 */
export type DecompositionKind =
  | 'dimensionless'
  | 'scalable-with-caveat'
  | 'earth-only'

/** 一条经验公式的拆解。 */
export interface EmpiricalNote {
  /** 公式 id。 */
  id: string
  /** 中文名。 */
  name: string
  /** 原表达式。 */
  expr: string
  /** 拆解级别。 */
  kind: DecompositionKind
  /**
   * **底层原理**：这条式子真正的起点是什么。
   *
   * 与 `bakedIn` 的区别：bakedIn 说「哪个数字藏了什么」，
   * principle 说「物理上为什么会有这条式子」。
   */
  principle: string
  /** 被烘焙的常数（原本藏起来的量）。 */
  bakedIn?: string
  /**
   * 泛化后**形式仍然成立**的部分（不含数值系数）。
   *
   * 写成「量纲正确但系数待定」的形式，让作者知道哪些能留、哪些要自己标。
   */
  genericForm?: string
  /** 泛化后**必须重新标定**的系数（以及为什么）。 */
  retuneNeeded?: string
  /** 泛化后需要哪些物理量。 */
  needsFrom?: string[]
  /** 在什么条件下**形式本身**就失效（不是系数不准，而是式子不该用）。 */
  breaksWhen?: string
  /** 一句话给作者。 */
  advice: string
}

