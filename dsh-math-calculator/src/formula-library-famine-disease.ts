/**
 * 公式库第二十七批：**瘟疫、饥荒与生存（P1）—— 前工业社会的两大死因**。
 *
 * ## 为什么这批是硬缺口
 *
 * 缺口分析的实测结论：从「资源不足」到「人会死」这条链**中间是断的**。
 *
 * ```
 *   ① 算热量需求     ✅ 有（metabolic_generic 等）
 *   ② 算缺口比例     ⚠ 零散
 *   ③ 算存活时间     ❌ 0 条
 *   ④ 算死亡率       ❌ 0 条
 * ```
 *
 * 而饥荒与瘟疫是前工业社会**最核心的两大死亡机制**。缺这两块，
 * 「这个县缺粮三成」这句话就没法往下写。
 *
 * ## 收严的判据：不是所有「流行模型」都能做成闭合式
 *
 * SIR 的**最终感染规模**是个超越方程（R_∞ = 1 − e^(−R0·R_∞)），
 * 必须迭代求解。所以**本批不收它** —— 它已由 `ode` 时程配方覆盖（见 recipe-process）。
 *
 * 只收有真闭式的：
 *
 * ```
 *   收：倍增时间、世代间隔、清除阈值、存活时间、缺口比例
 *   不收：最终规模（超越方程）、峰值时间（无闭式）、死亡率曲线（需经验表）
 * ```
 *
 * 第二类不收的东西不是「不重要」，而是「写成一条 expr 会给出看似精确的错数」。
 * 前者请用 `ode` + `recipe-process`，后者请查经验表。
 *
 * @module dsh-math-calculator/formula-library-famine-disease
 */

