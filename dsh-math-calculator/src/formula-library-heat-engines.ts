/**
 * 公式库第二十四批：**热机循环与制冷（19—20 世纪工程的核心）**。
 *
 * ## 为什么这批是真空缺
 *
 * 库里 thermodynamics 有 17 条，但**全是「物性」而非「循环」**：
 *
 * ```
 *   已有：理想气体、热容、潜热、导热、卡诺效率、卡诺 COP、熵变
 *   没有：Rankine（蒸汽动力）、Otto（内燃）、Diesel、Brayton（燃气轮机）、
 *         制冷循环的实际 COP、再热/回热
 * ```
 *
 * 后果很直接：**卡诺效率只是「天花板」，而真实机器从来达不到它。**
 * 只有引入循环形式，才能回答「这台蒸汽机效率 8% 是差还是已经接近极限」——
 * 而这个问题恰恰是「技术树能做到哪一级」的判据。
 *
 * ## 本批的核心区分（也是最容易写错的地方）
 *
 * ```
 *   卡诺效率         = 1 − Tc/Th        仅取决于温度，是**上限**
 *   Rankine 效率     = 卡诺 × 内部效率   真实蒸汽循环，受限于泵功与不可逆
 *   Otto 效率        = 1 − r^(1−γ)      取决于**压缩比**，与温度无关
 * ```
 *
 * 把 Otto 的效率公式套到蒸汽机上，或者反过来，都会得到完全错误的结论。
 * 这两者的区别是**热机技术树分叉的物理依据**：
 *
 * ```
 *   蒸汽机  受温度限制（材料耐热）→ 想提高效率必须提温提压
 *   内燃机  受压缩比限制（爆震）  → 想提高效率必须提压缩比
 * ```
 *
 * ## 一处必须说明的白盒假设
 *
 * 所有循环都按**理想气体/理想循环**计算，没有不可逆损失。
 * 真实效率要乘「相对内效率」（蒸汽机 0.5~0.7、内燃机 0.7~0.85）。
 * 这一点写进每条 desc，因为它决定了「算出的数能不能直接用」。
 *
 * @module dsh-math-calculator/formula-library-heat-engines
 */

