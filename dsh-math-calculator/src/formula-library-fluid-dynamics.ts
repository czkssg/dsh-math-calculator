/**
 * 公式库第二十五批：**流体力学与空气动力（能不能飞、船能多快）**。
 *
 * ## 为什么这批是真正的空白
 *
 * 库里 physics/fluid 只有 6 条、engineering/fluid 4 条，全是「静力学与管流」：
 *
 * ```
 *   已有：静水压、浮力、流量、雷诺数、弗劳德数、达西损失、泵功率、孔口出流
 *   没有：伯努利、升力、阻力、边界层、Stokes 沉降、马赫角、边界层转捩
 * ```
 *
 * 也就是说：**库里能算「水有多深压多大」，但算不了「这东西能不能飞起来」。**
 * 而后者恰恰是所有架空设定最想回答的问题之一。
 *
 * ## 本批最该区分清楚的一件事：两种「阻力」
 *
 * ```
 *   压差阻力（形状阻力）  ∝ ½ρv²·A·Cd    与**速度平方**成正比
 *   摩擦阻力（粘性阻力）  ∝ v（层流）      与速度**一次方**成正比
 * ```
 *
 * 低速时摩擦阻力主导、高速时压差阻力主导 —— **所以「把船体做光滑」与「把船体做瘦」
 * 在不同速度下价值完全不同**。这条区分是船舶与飞机设计的根本分水岭。
 *
 * ## 一处必须写明的边界
 *
 * 所有公式都是**定常、不可压、牛顿流体**。
 * 跨声速与超声速要另用可压缩关系（本批只给马赫角与临界马赫）。
 * 这一条写进 desc，因为它决定了「算出来的数在什么范围内能用」。
 *
 * @module dsh-math-calculator/formula-library-fluid-dynamics
 */

