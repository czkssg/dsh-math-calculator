/**
 * 公式库第二十批：**冷战到千禧年的支柱学科（二）—— 运筹学、系统工程、可靠性**。
 *
 * ## 为什么这一批是「管理与决策的物理学」
 *
 * 前一批（控制论/信息论）处理**信号与调节**，这一批处理**资源与选择**。
 * 但它们的地位是同级的：1940—1960 的战争与工业规模，逼出了这两套语言。
 *
 * ```
 *   运筹学    0 条   ← 排队、库存、排队网络 —— 后勤与调度的一切基础
 *   博弈论    0 条   ← 只有 tragedy_commons，没有零和与均衡
 *   系统工程  0 条   ← 只有 fatigue_life，没有可靠性串并联
 * ```
 *
 * ## 收录判据里最该注意的一条
 *
 * **运筹学的大部分教材内容建模依赖「解线性规划」**，而这需要单纯形法迭代，
 * 不是闭合式。所以本批只收**有闭式解的那一层**：
 *
 * ```
 *   收：Little 定律、EOQ、Erlang 排队、报童问题的临界比
 *   不收：一般线性规划的求解（用 ode/recurrence 或手算，不该塞进公式库）
 * ```
 *
 * 这个取舍很重要：把「需要迭代才能算的东西」硬做成「一条 expr」，
 * 结果是给出一个看似精确的错数 —— 这正是本项目一直在打击的。
 *
 * ## 一处口径说明
 *
 * 库的 expr 经 mathjs，无 `ln`（用 `log`）、无 `ceil/floor`。
 * 涉及取整的量（如「需要几个窗口」）一律给连续值，并在 desc 写明向上取整。
 *
 * @module dsh-math-calculator/formula-library-or
 */

