/**
 * 公式库第二十六批：**化学工程单元操作（能不能量产酸、碱、药）**。
 *
 * ## 缺口：23 条化学公式全是「实验室」，没有一条「工厂」
 *
 * ```
 *   已有：摩尔、浓度、滴定、pH、溶度积、能斯特、阿伦尼乌斯、吉布斯能
 *   没有：反应器尺寸、转化率、传质、萃取级数、精馏板数、吸附穿透、干燥
 * ```
 *
 * 这个区别不是「多几条」，而是**能不能回答「这个文明造不造得出成吨的硫酸」**：
 *
 * ```
 *   实验室问题：这杯溶液 pH 多少（已有）
 *   工业问题：  这个反应釜一天能产多少、要多大、几级萃取够（全空）
 * ```
 *
 * ## 本批的判据：只收「能决定装置尺寸」的式子
 *
 * 化学工程的核心是**放大**（scale-up）。而放大问题的共性是最关键的：
 *
 * ```
 *   停留时间 τ = V/Q        → 决定反应器/萃取塔/干燥器的**体积**
 *   级数（N 级萃取、精馏板）→ 决定设备的**高度**
 *   传质系数 k_L·a          → 决定设备能多快达到平衡
 * ```
 *
 * 所以本批全部围绕这三个量组织，而不是按「单元操作名称」罗列。
 *
 * ## 一处必须写明的限制
 *
 * 真实的化学工程**大量依赖实验关联式**（传质系数、板效率、干燥曲线），
 * 本批只给**结构式与量级**，具体系数必须查手册或实验。
 * 这一条写进每条的 desc —— 否则用户会以为算出的数可以直接施工。
 *
 * @module dsh-math-calculator/formula-library-chemical-engineering
 */

